#!/usr/bin/env python3
"""Generates protocol/test-vectors.json (stdlib only).

Swift, Dart and the Node reference implementation must all reproduce these
values exactly; each has a test that reads the generated file.
"""
import base64, hashlib, hmac, json, pathlib

def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()

def mac(key: bytes, msg: str) -> bytes:
    return hmac.new(key, msg.encode("utf-8"), hashlib.sha256).digest()

token = bytes(range(32))                       # 00 01 02 ... 1f
device_id = "phone-0123456789abcdef"
client_nonce = b64u(bytes(range(0x40, 0x50)))  # 16 bytes
server_nonce = b64u(bytes(range(0x80, 0x90)))  # 16 bytes

secret = mac(token, f"secret|{device_id}|{client_nonce}|{server_nonce}")

# Part 2: signed input frames
session_key = mac(secret, f"session|{client_nonce}|{server_nonce}")
input_seq = 7
input_body = '{"ev":[{"e":"move","dx":5,"dy":-3},{"e":"btn","b":"left","s":"down","n":1}]}'

vectors = {
    "comment": "Generated by protocol/tools/gen_vectors.py - do not edit by hand.",
    "protocolVersion": 1,
    "token": b64u(token),
    "deviceId": device_id,
    "clientNonce": client_nonce,
    "serverNonce": server_nonce,
    "pairProof": b64u(mac(token, f"pair|{device_id}|{client_nonce}|{server_nonce}")),
    "secret": b64u(secret),
    "authProof": b64u(mac(secret, f"auth|{device_id}|{client_nonce}|{server_nonce}")),
    "serverProof": b64u(mac(secret, f"server|{server_nonce}|{client_nonce}")),
    "sessionKey": b64u(session_key),
    "inputSeq": input_seq,
    "inputBody": input_body,
    "inputMac": b64u(mac(session_key, f"input|{input_seq}|{input_body}")),
}
out = pathlib.Path(__file__).resolve().parent.parent / "test-vectors.json"
out.write_text(json.dumps(vectors, indent=2) + "\n")
print("wrote", out)
